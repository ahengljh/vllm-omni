#!/usr/bin/env python3

from __future__ import annotations

import argparse
from pathlib import Path


def parse_devices(value: str) -> list[int]:
    devices = [int(part.strip()) for part in value.split(",") if part.strip()]
    if not devices:
        raise ValueError("device list cannot be empty")
    return devices


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=("Materialize a Bagel AR->DiT split stage-config YAML from simple TP / CFG-parallel inputs.")
    )
    parser.add_argument("--output", required=True, help="Output YAML path")
    parser.add_argument(
        "--ar-devices",
        default="0",
        help="Comma-separated devices for stage-0 AR/LLM (default: 0)",
    )
    parser.add_argument(
        "--tp-size",
        type=int,
        default=1,
        help="Diffusion tensor_parallel_size for stage-1 (default: 1)",
    )
    parser.add_argument(
        "--cfg-size",
        type=int,
        default=1,
        choices=[1, 2, 3],
        help="Diffusion cfg_parallel_size for stage-1 (default: 1)",
    )
    parser.add_argument(
        "--dit-start-device",
        type=int,
        default=1,
        help="First device index for stage-1 when --dit-devices is omitted (default: 1)",
    )
    parser.add_argument(
        "--dit-devices",
        default="",
        help="Explicit comma-separated devices for stage-1 diffusion",
    )
    parser.add_argument(
        "--ar-gpu-memory-utilization",
        type=float,
        default=0.45,
        help="Stage-0 gpu_memory_utilization to write into YAML (default: 0.45)",
    )
    parser.add_argument(
        "--dit-gpu-memory-utilization",
        type=float,
        default=0.45,
        help="Stage-1 gpu_memory_utilization to write into YAML (default: 0.45)",
    )
    parser.add_argument(
        "--max-num-batched-tokens",
        type=int,
        default=32768,
        help="max_num_batched_tokens written to both stages (default: 32768)",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()

    stage1_world_size = args.tp_size * args.cfg_size
    if stage1_world_size <= 0:
        raise ValueError("tp-size * cfg-size must be > 0")

    if args.dit_devices:
        dit_devices = parse_devices(args.dit_devices)
    else:
        dit_devices = list(range(args.dit_start_device, args.dit_start_device + stage1_world_size))

    if len(dit_devices) != stage1_world_size:
        raise ValueError(
            f"stage-1 requires {stage1_world_size} device(s) for tp-size={args.tp_size} and cfg-size={args.cfg_size}, "
            f"but got {len(dit_devices)} device(s): {dit_devices}"
        )

    ar_devices = parse_devices(args.ar_devices)

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    yaml_text = f'''# Auto-generated by materialize_split_stage_config.py
stage_args:
  - stage_id: 0
    stage_type: llm
    prompt_expand_func: vllm_omni.model_executor.stage_input_processors.bagel.expand_cfg_prompts
    runtime:
      devices: "{",".join(str(d) for d in ar_devices)}"
      max_batch_size: 3
    engine_args:
      model_stage: thinker
      model_arch: OmniBagelForConditionalGeneration
      worker_type: ar
      scheduler_cls: vllm_omni.core.sched.omni_ar_scheduler.OmniARScheduler
      gpu_memory_utilization: {args.ar_gpu_memory_utilization}
      enforce_eager: true
      trust_remote_code: true
      engine_output_type: text
      distributed_executor_backend: "mp"
      enable_prefix_caching: true
      max_num_batched_tokens: {args.max_num_batched_tokens}
      tensor_parallel_size: 1
      omni_kv_config:
        need_send_cache: true
        kv_transfer_criteria:
          type: prefill_finished
    final_output: true
    final_output_type: text
    is_comprehension: true

  - stage_id: 1
    stage_type: diffusion
    cfg_kv_collect_func: vllm_omni.model_executor.stage_input_processors.bagel.collect_cfg_kv_caches
    runtime:
      devices: "{",".join(str(d) for d in dit_devices)}"
      max_batch_size: 1
    engine_args:
      model_stage: dit
      gpu_memory_utilization: {args.dit_gpu_memory_utilization}
      enforce_eager: true
      trust_remote_code: true
      engine_output_type: image
      distributed_executor_backend: "mp"
      enable_prefix_caching: false
      max_num_batched_tokens: {args.max_num_batched_tokens}
      tensor_parallel_size: {args.tp_size}
      cfg_parallel_size: {args.cfg_size}
      omni_kv_config:
        need_recv_cache: true
    engine_input_source: [0]
    final_output: true
    final_output_type: image
    is_comprehension: false

runtime:
  enabled: true
  defaults:
    window_size: -1
    max_inflight: 1
  connectors:
    shared_memory_connector:
      name: SharedMemoryConnector
      extra:
        shm_threshold_bytes: 65536
  edges:
    - from: 0
      to: 1
      window_size: -1
'''
    output_path.write_text(yaml_text, encoding="utf-8")
    print(output_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
